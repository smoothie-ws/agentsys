'use strict';
// Rebuild the browser/backend package after editing plugins/ai.
const fs = require('node:fs'),
  path = require('node:path');
const root = path.resolve(__dirname, '..'),
  source = path.join(root, 'plugins', 'ai');
require('../plugins/ai/nodes/build.cjs');
const files = {};
function collect(directory, prefix = '') {
  for (const entry of fs.readdirSync(directory, {withFileTypes: true}).sort((a, b) => a.name.localeCompare(b.name))) {
    const relative = prefix + entry.name,
      filename = path.join(directory, entry.name);
    if (entry.isDirectory()) collect(filename, relative + '/');
    else if (relative !== 'manifest.json')
      files[relative] = relative.endsWith('.png')
        ? 'data:image/png;base64,' + fs.readFileSync(filename).toString('base64')
        : fs.readFileSync(filename, 'utf8');
  }
}
collect(source);
const pkg = {
  format: 'agentsys.plugin/2',
  manifest: JSON.parse(fs.readFileSync(path.join(source, 'manifest.json'), 'utf8')),
  files,
};
fs.writeFileSync(
  path.join(root, 'js', 'backend', 'builtin-plugins.js'),
  "// Generated by tools/build-builtin-plugins.js from plugins/ai.\n'use strict';\nconst BUILTIN_PLUGINS = " +
    JSON.stringify([pkg], null, 2) +
    ';\n'
);
