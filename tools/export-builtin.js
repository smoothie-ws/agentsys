'use strict';
// Regenerates js/backend/builtin-nodes.js (the built-in Library catalog) from the Library of a running server:
//   node tools/export-builtin.js http://127.0.0.1:8080 [AGENTSYS_TOKEN]
// Every Library node of that server becomes a built-in node. Review the diff, then commit.
const fs = require('node:fs');
const path = require('node:path');

const [base = 'http://127.0.0.1:8080', token] = process.argv.slice(2);
(async () => {
  const response = await fetch(base.replace(/\/$/, '') + '/api/resources', {
    headers: {'X-AgentSys': '1', ...(token ? {Authorization: 'Bearer ' + token} : {})},
  });
  if (!response.ok) throw new Error(`GET /api/resources answered ${response.status}`);
  const nodes = (await response.json())
    .filter(r => !r.id.startsWith('plugin.')) // a plugin's nodes come with the plugin
    .map(r => ({name: r.name, payload: r.payload}))
    .sort((a, b) => a.name.localeCompare(b.name, undefined, {sensitivity: 'base'}));
  const file = path.join(__dirname, '..', 'js', 'backend', 'builtin-nodes.js');
  const text = `// The built-in Library catalog: nodes that come with the app (flow control, values, waits). Generated by
// tools/export-builtin.js from a Library; do not edit by hand. routes-builtin.js adds them to a Library that lacks them.
'use strict';

const BUILTIN_NODES = [
${nodes.map(n => '  ' + JSON.stringify(n)).join(',\n')}
];
`;
  fs.writeFileSync(file, text);
  console.log(`${nodes.length} nodes written to ${path.relative(process.cwd(), file)} (${text.length} bytes)`);
})().catch(error => {
  console.error(error.message);
  process.exit(1);
});
